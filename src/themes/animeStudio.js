export function resolveAssetUrl(relPath) {
  if (!relPath) return '';
  if (relPath.startsWith('http') || relPath.startsWith('data:') || relPath.startsWith('chrome-extension:')) {
    return relPath;
  }
  if (typeof chrome !== 'undefined' && chrome.runtime?.getURL) {
    return chrome.runtime.getURL(relPath);
  }
  return '/' + relPath.replace(/^\//, '');
}
